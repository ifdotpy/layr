//! Errors in canonical object encodings.
#[derive(Debug)]
pub enum Error {
    VarintOverflow,
    NonminimalVarint,
    TreeVersion,
    EntryOrder,
    SymlinkMode,
    SymlinkTarget,
    XattrName,
    XattrOrder,
    HardLinkCount,
    HardLinkPath,
    HardLinkPathOrder,
    HardLinkGroupOrder,
    TrailingTree,
    NoncanonicalTree,
    Truncated,
    TimesVersion,
    TimesCount,
    CloudVersion,
    TrailingTimes,
    AmbiguousTimesVersion,
    PackIndexShort,
    PackChecksum,
    PackMagic,
    PackIndexTruncated,
    PackBlockLayout,
    PackIndexLength,
    PackEntryForm,
    PackEntryRange,
    PackEntryOrder,
    PackId,
    PackBlockRange,
    PackMissingBlock,
    CloudCount,
    CloudRoot,
    CloudOutsideRoot,
    CloudParentSpan,
    NoncanonicalCloudTimes,
    EmptyScratch,
    Read(std::io::Error),
    LooseHeader,
    LooseForm(u8),
    CloudSpan,
    LegacyCloudVersion,
    Integer(std::num::TryFromIntError),
    UnknownKind(u8),
    LengthMismatch,
    EntryName(Vec<u8>),
    Mode(u32),
    EntryType(u8),
    TimesRecord(u8),
    ExcludedXattr(Vec<u8>),
    PackDataLength { actual: u64, indexed: u64 },
}
impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::VarintOverflow => f.write_str("a varint is too large"),
            Self::NonminimalVarint => f.write_str("a varint is not minimal"),
            Self::TreeVersion => f.write_str("unknown tree format version"),
            Self::EntryOrder => f.write_str("tree entries are not sorted or not unique"),
            Self::SymlinkMode => f.write_str("a symbolic link has mode 0 in a tree"),
            Self::SymlinkTarget => f.write_str("invalid symbolic link target"),
            Self::XattrName => f.write_str("invalid extended attribute name"),
            Self::XattrOrder => f.write_str("extended attributes are not sorted or not unique"),
            Self::HardLinkCount => f.write_str("a hard link group has fewer than two paths"),
            Self::HardLinkPath => f.write_str("invalid hard link path"),
            Self::HardLinkPathOrder => f.write_str("hard link paths are not sorted or not unique"),
            Self::HardLinkGroupOrder => f.write_str("hard link groups are not sorted"),
            Self::TrailingTree => f.write_str("bytes after the tree"),
            Self::NoncanonicalTree => f.write_str("noncanonical tree encoding"),
            Self::Truncated => f.write_str("the object ends early"),
            Self::TimesVersion => f.write_str("unknown times format version"),
            Self::TimesCount => f.write_str("a times table has a wrong count"),
            Self::CloudVersion => f.write_str("unknown Cloud times format"),
            Self::TrailingTimes => f.write_str("bytes after the times table"),
            Self::AmbiguousTimesVersion => f.write_str("times version 1 has two layouts; migrate it with an explicit layout"),
            Self::PackIndexShort => f.write_str("a pack index is too short"),
            Self::PackChecksum => f.write_str("a pack index does not match its checksum"),
            Self::PackMagic => f.write_str("not a pack index"),
            Self::PackIndexTruncated => f.write_str("a pack index is cut short"),
            Self::PackBlockLayout => f.write_str("pack blocks are not contiguous"),
            Self::PackIndexLength => f.write_str("a pack index has the wrong length"),
            Self::PackEntryForm => f.write_str("unknown pack entry form"),
            Self::PackEntryRange => f.write_str("a pack entry leaves its block"),
            Self::PackEntryOrder => f.write_str("pack entries are not sorted or not unique"),
            Self::PackId => f.write_str("the pack index names another pack"),
            Self::PackBlockRange => f.write_str("a pack block leaves the data file"),
            Self::PackMissingBlock => f.write_str("a pack entry names a missing block"),
            Self::CloudCount => f.write_str("invalid Cloud times count"),
            Self::CloudRoot => f.write_str("invalid Cloud times root"),
            Self::CloudOutsideRoot => f.write_str("Cloud time is outside the root"),
            Self::CloudParentSpan => f.write_str("Cloud times span leaves its parent"),
            Self::NoncanonicalCloudTimes => f.write_str("noncanonical Cloud times"),
            Self::EmptyScratch => f.write_str("hash scratch memory is empty"),
            Self::Read(e) => e.fmt(f),
            Self::LooseHeader => f.write_str("no valid loose object header"),
            Self::LooseForm(b) => write!(f, "unknown loose object form {b:#x}"),
            Self::CloudSpan => f.write_str("Cloud times span is out of bounds"),
            Self::LegacyCloudVersion => f.write_str("not a Cloud version 1 times table"),
            Self::Integer(e) => e.fmt(f),
            Self::UnknownKind(b) => write!(f, "unknown object kind byte {b:#x}"),
            Self::LengthMismatch => {
                f.write_str("the content length differs from its header (the file changed while it was read)")
            }
            Self::EntryName(n) => write!(f, "invalid entry name {:?}", String::from_utf8_lossy(n)),
            Self::Mode(m) => write!(f, "invalid mode {m:o}"),
            Self::EntryType(k) => write!(f, "unknown entry type {k}"),
            Self::TimesRecord(r) => write!(f, "unknown times record {r}"),
            Self::ExcludedXattr(n) => write!(f, "a tree does not keep extended attribute {}", String::from_utf8_lossy(n)),
            Self::PackDataLength { actual, indexed } => write!(f, "the pack data has {actual} bytes, its index says {indexed}"),
        }
    }
}
impl std::error::Error for Error {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Read(e) => Some(e),
            Self::Integer(e) => Some(e),
            _ => None,
        }
    }
}
impl From<std::num::TryFromIntError> for Error {
    fn from(e: std::num::TryFromIntError) -> Self {
        Self::Integer(e)
    }
}
